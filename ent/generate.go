//go:build ignore

package main

import (
	"fmt"
	"log"

	"entgo.io/ent/entc"
	"entgo.io/ent/entc/gen"
)

func main() {
	err := entc.Generate("./internal/models", &gen.Config{
		Header: `// Code generated by ent, DO NOT EDIT.`,
	})
	if err != nil {
		log.Fatal("running ent codegen:", err)
	}
	fmt.Println("Ent code generation completed successfully")
}