package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"
	"time"

	"entgo.io/ent/entc"
	"entgo.io/ent/entc/gen"
	"github.com/wuwuseo/ent/extension/tableprefix"
)

func main() {
	target, err := os.MkdirTemp("", "go-admin-entgen-")
	if err != nil {
		log.Fatal(err)
	}
	defer os.RemoveAll(target)
	err = entc.Generate("./schema", &gen.Config{
		Target:  target,
		Package: "go-admin/internal/ent",
		Hooks: []gen.Hook{
			EnsureStructTag("json"),
		},
	},
		entc.Extensions(tableprefix.NewTablePrefix()),
	)
	if err != nil {
		log.Fatalf("running ent codegen: %v", err)
	}
	if err := generateTablePrefixInitializer(target, "go-admin/internal/ent"); err != nil {
		log.Fatalf("generating table prefix initializer: %v", err)
	}
	if err := installGenerated(target, "."); err != nil {
		log.Fatalf("installing ent codegen: %v", err)
	}
}

// Every generated entity package owns table variables, including relationship
// tables. Build their initializer from Ent's formatted output so new feature
// schemas require no hand-maintained prefix list.
func generateTablePrefixInitializer(target, importBase string) error {
	entries, err := os.ReadDir(target)
	if err != nil {
		return err
	}
	type entityPackage struct {
		name   string
		tables []string
	}
	var packages []entityPackage
	for _, entry := range entries {
		if !entry.IsDir() {
			continue
		}
		name := entry.Name()
		file := filepath.Join(target, name, name+".go")
		parsed, err := parser.ParseFile(token.NewFileSet(), file, nil, 0)
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return err
		}
		var tables []string
		hasPrefix := false
		for _, decl := range parsed.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.VAR {
				continue
			}
			for _, spec := range gen.Specs {
				for _, ident := range spec.(*ast.ValueSpec).Names {
					if ident.Name == "TablePrefix" {
						hasPrefix = true
					} else if ident.Name == "Table" || strings.HasSuffix(ident.Name, "Table") {
						tables = append(tables, ident.Name)
					}
				}
			}
		}
		if !hasPrefix || len(tables) == 0 {
			continue
		}
		sort.Strings(tables)
		packages = append(packages, entityPackage{name: name, tables: tables})
	}
	sort.Slice(packages, func(i, j int) bool { return packages[i].name < packages[j].name })
	var b bytes.Buffer
	b.WriteString("// Code generated by entc.go; DO NOT EDIT.\npackage ent\n\nimport (\n\"strings\"\n")
	fmt.Fprintf(&b, "%q\n", importBase+"/migrate")
	for _, pkg := range packages {
		fmt.Fprintf(&b, "%q\n", importBase+"/"+pkg.name)
	}
	b.WriteString(")\n\nfunc initGeneratedTablePrefixes(prefix string) {\n")
	for _, pkg := range packages {
		fmt.Fprintf(&b, "{\nold := %s.TablePrefix\n%s.TablePrefix = prefix\n", pkg.name, pkg.name)
		for _, table := range pkg.tables {
			fmt.Fprintf(&b, "%s.%s = prefix + strings.TrimPrefix(%s.%s, old)\n", pkg.name, table, pkg.name, table)
		}
		b.WriteString("}\n")
	}
	b.WriteString("old := migrate.TablePrefix\nmigrate.TablePrefix = prefix\nfor _, table := range migrate.Tables { table.Name = prefix + strings.TrimPrefix(table.Name, old) }\n}\n")
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(target, "zz_tableprefix_gen.go"), formatted, 0o644)
}

// Generate into a temporary directory first: Ent writes raw templates before
// formatting them, so a transient Windows file mapping must not corrupt the
// checked-in generated client. Unchanged files are not rewritten.
func installGenerated(from, to string) error {
	return filepath.WalkDir(from, func(path string, entry os.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() {
			return nil
		}
		rel, err := filepath.Rel(from, path)
		if err != nil {
			return err
		}
		output := filepath.Join(to, rel)
		content, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if current, err := os.ReadFile(output); err == nil && bytes.Equal(current, content) {
			return nil
		}
		if err := os.MkdirAll(filepath.Dir(output), 0o755); err != nil {
			return err
		}
		for attempt := 0; attempt < 30; attempt++ {
			if err = os.WriteFile(output, content, 0o644); err == nil {
				return nil
			}
			time.Sleep(100 * time.Millisecond)
		}
		return fmt.Errorf("write %s: %w", output, err)
	})
}

// EnsureStructTag 字段确保所有的字段都有标签
func EnsureStructTag(name string) gen.Hook {
	return func(next gen.Generator) gen.Generator {
		return gen.GenerateFunc(func(g *gen.Graph) error {
			for _, node := range g.Nodes {
				for _, field := range node.Fields {
					tag := reflect.StructTag(field.StructTag)
					if _, ok := tag.Lookup(name); !ok {
						return fmt.Errorf("struct tag %q is missing for field %s.%s", name, node.Name, field.Name)
					}
				}
			}
			return next.Generate(g)
		})
	}
}
